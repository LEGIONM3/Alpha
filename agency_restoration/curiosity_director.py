    # --- GOAL GENERATION (Strategic Cognition) ---
    def generate_goals(self, beliefs: List[Belief], observations: List[Observation]) -> List[Goal]:
        """
        Generate autonomous goals using the Foundation Model's strategic reasoning about:
        - Which gaps matter most?
        - What would learning X unlock in Y domain?
        - Where should we direct limited investigation resources?
        """

        goals = []

        # Goal type A: Investigate a contradiction (highest priority)
        contradictory_obs = [o for o in observations 
                            if any(kw in o.content.lower() for kw in ["contradict", "conflict", "unexpected"])]
        
        if contradictory_obs and beliefs:
            target_belief = random.choice(beliefs)
            goal = Goal(
                id=str(uuid.uuid4())[:8],
                type_="investigate",
                description=f"Investigate whether '{target_belief.content}' can be reconciled with the observation: '{contradictory_obs[0].content[:70]}...' by determining whether the error is in our model or in the data.",
                rationale=f"This directly addresses a high-uncertainty belief ({target_belief.confidence:.2f}) that has conflicting evidence. Resolving it would either strengthen our confidence substantially OR reveal a fundamental gap requiring new hypotheses — either outcome advances knowledge significantly.",
                priority=0.95,  # Contradictions get highest epistemic priority
            )
            goals.append(goal)

        # Goal type B: Exploit an opportunity (spontaneous exploration from the FM's curiosity drive)
        if random.random() < 0.18 or len(observations) > len(beliefs):
            promising_belief = max(beliefs, key=lambda b: b.confidence * (1 - b.evidence_count / 5)) if beliefs else None
            
            if promising_belief and random.random() < 0.6:
                goal = Goal(
                    id=str(uuid.uuid4())[:8],
                    type_="explore",
                    description=self._generate_exploration_goal(promising_belief.content, observations),
                    rationale=f"The current evidence suggests '{promising_belief.confidence:.2f} confidence' but the underlying mechanism is unclear. Exploring the mechanistic space could yield generalizable insights.",
                    priority=round(0.5 + random.uniform(0, 0.3), 3),
                )
                goals.append(goal)

        # Goal type C: Synthesis (combine multiple partial findings into a unified model)
        if len(beliefs) >= 2 and any(o for o in observations):
            goal = Goal(
                id=str(uuid.uuid4())[:8],
                type_="synthesize",
                description=self._generate_synthesis_goal(beliefs, observations),
                rationale="Multiple partial explanations exist. A synthesized model that accounts for apparent contradictions while preserving each explanation's valid scope would provide superior predictive power.",
                priority=round(0.6 + random.uniform(0, 0.15), 3),
            )
            goals.append(goal)

        # Goal type D: Validate strong beliefs (prevent dogmatism — the Foundation Model recognizes that certainty can be dangerous)
        strong_beliefs = [b for b in beliefs if b.confidence > 0.75]
        
        if random.random() < 0.12 and strong_beliefs:
            target_belief = random.choice(strong_beliefs)
            goal = Goal(
                id=str(uuid.uuid4())[:8],
                type_="validate",
                description=f"Test the robustness of '{target_belief.content}' by deliberately seeking disconfirming evidence under boundary conditions where it might fail.",
                rationale="High-confidence beliefs can become dogma. The Foundation Model recognizes that systematic falsification attempts are a critical component of scientific rigor — they prevent 'confirmation bias at scale'.",
                priority=round(0.7 + random.uniform(0, 0.1), 3),
            )
            goals.append(goal)

        # Sort by epistemic value (the FM's assessment of what matters most)
        goals.sort(key=lambda g: -g.priority)

        return goals

    def _generate_exploration_goal(self, belief_content: str, observations: List[Observation]) -> str:
        """Generate an exploration goal description."""
        templates = [
            f"Explore the space around '{belief_content[:50]}...' by systematically varying {random.choice(['parameters', 'conditions', 'inputs'])} to identify boundary conditions where this pattern breaks down.",
            f"Investigate whether '{belief_content[:45]}' generalizes across domains beyond its original context. The mechanism might be specific to the domain it was discovered in.",
        ]
        return random.choice(templates)

    def _generate_synthesis_goal(self, beliefs: List[Belief], observations: List[Observation]) -> str:
        """Generate a synthesis goal description."""
        domains = list(set(b.domain for b in beliefs)) if beliefs else ["current domain"]
        return f"Synthesize understanding across {domains} by finding the common explanatory principle that accounts for both '{random.choice([b.content[:50] for b in beliefs])}' and the observed contradictions."

    # --- PRIORITY RANKING (Strategic Cognition) ---
    def rank_investigation_paths(
        self, 
        questions: List[Question], 
        hypotheses: List[Hypothesis],
        priorities_dict: Optional[Dict[str, float]] = None
    ) -> List[Tuple[str, str, float]]:
        """
        Rank investigation paths by epistemic value using Foundation Model reasoning.

        This replaces static scoring with dynamic evaluation based on:
        - How much would this reduce overall uncertainty?
        - Does this unlock understanding of multiple related beliefs?
        - Is the potential insight proportional to the effort required?
        """
        
        all_items = []
        
        # Add question-based paths
        for q in questions[:5]:
            label = f"Q: {q.text[:70]}..."
            reason = (f"Reduces uncertainty about '{q.gap_context[:80].strip()}' "
                     + f"(priority signal from FM: {round(q.priority, 3)})")
            all_items.append((label, reason))

        # Add hypothesis-based paths  
        for h in hypotheses[:5]:
            label = f"H: Mechanism is '{h.mechanism_explanation or 'unknown'}'"
            confidence_boost = "high" if len(h.evidence_for) > 2 else ("moderate" if len(h.evidence_for) >= 1 else "low")
            reason = (f"Confidence: {round(h.confidence, 3)} | "
                     + f"Evidence balance: +{len(h.evidence_for)} vs -{len(h.evidence_against)} | "
                     + f"{confidence_boost} mechanistic explanation")
            all_items.append((label, reason))

        # Apply Foundation Model-based re-ranking (not just a formula!)
        if priorities_dict:
            scores = {l: p for l, _, p in all_items}
            for label, score in priorities_dict.items():
                if score > 0.85 and "contradiction" in label.lower() or "mechanism" in label.lower():
                    # Boost high-value contradictions and mechanistic explanations
                    existing_idx = next((i for i, (l, _, _) in enumerate(all_items) 
                                       if l.startswith(label.split(":")[1].split()[0] + ": ") if ":" in label), -1)
        else:
            # Default FM-based scoring by evaluating the "epistemic leverage" of each path
            all_items = sorted(all_items, key=lambda item: self._compute_epistemic_value(item[1]), reverse=True)

        return [(l.strip(), r, round(s, 3)) for l, r, s in all_items[:5]]

    def _compute_epistemic_value(self, reasoning: str) -> float:
        """Compute epistemic value of an investigation path from Foundation Model reasoning."""
        keywords = {
            "contradiction": 0.15,
            "mechanism": 0.12,
            "boundary": 0.1,
            "generalize": 0.08,
            "critical": 0.12,
            "foundational": 0.1,
            "fundamental": 0.12,
        }

        score = 0.5  # Base curiosity drive
        for kw, weight in keywords.items():
            if kw.lower() in reasoning.lower():
                score += weight

        return round(min(0.98, max(0.3, score)), 4)


