                target_gap=question.gap_context[:100],
                confidence=0.62,
                evidence_for=["JIT deoptimization patterns show bytecode-level differences between typed and untyped paths"],
                evidence_against=["No measurable difference observed in micro-benchmarks without framework overhead"],
