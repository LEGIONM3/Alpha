class WorldModelManager:
    """Manages the agent's internal world model (beliefs + observations)."""

    def __init__(self):
        self.beliefs: Dict[str, Belief] = {}
        self.observations: List[Observation] = []

    def add_belief(self, belief: Belief) -> None:
        """Add a new belief to the world model."""
        self.beliefs[belief.id] = belief

    def update_confidence(self, belief_id: str, delta: float) -> Optional[float]:
        """
        Update confidence of a belief. The Foundation Model's strategic decisions drive this.
        
        In production, this would interface with a full verification engine that tracks
        evidence chains and applies Bayesian updating.
        """
        belief = self.beliefs.get(belief_id)
        if not belief:
            return None

        old_conf = belief.confidence
        
        # Update based on new evidence/contradiction
        belief.confidence = max(0.01, min(1.0, belief.confidence + delta))

        # Apply decay to unverified beliefs (prevents indefinite persistence of unsupported claims)
        if abs(delta) < 0.05 and not any(o.id == belief_id for o in self.observations[-5:]):
            # Belief hasn't been recently verified — apply slow decay
            decay_rate = 0.97
            belief.confidence *= decay_rate

        return round(belief.confidence, 4)

    def add_observation(self, observation: Observation) -> None:
        """Record a new observation from the environment."""
        self.observations.append(observation)


