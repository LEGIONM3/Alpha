"""Hypothesis Engine for Project Alpha.

Driven by the Foundation Model (Qwen 3.8 9B Heretic).
Generates falsifiable hypotheses grounded in empirical observations and research findings:
- hypothesis (statement)
- mechanism
- confidence
- evidence references
- falsification conditions

No heuristics. No scoring formulas. The Foundation Model decides.
"""

from __future__ import annotations

from datetime import datetime, timezone
import hashlib
import logging
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field, model_validator

from alpha.observation_engine.observation import Observation, ObservationRecord
from alpha.research_engine.engine import ResearchFinding
from alpha.reasoning.qwen_reasoner import (
    EvidenceBundle,
    StrategicReasoningResult,
    qwen_reasoner,
)

logger = logging.getLogger("alpha.hypothesizing.engine")


class Hypothesis(BaseModel):
    """A testable, falsifiable proposition derived from empirical evidence by the foundation model."""
    hypothesis_id: str = Field(default="")
    statement: str
    mechanism: str = Field(default="")
    confidence: float = Field(default=0.35, ge=0.0, le=1.0)
    evidence_references: List[str] = Field(default_factory=list)
    supporting_evidence_ids: List[str] = Field(default_factory=list)
    evidence_summary: str = Field(default="")
    falsification_conditions: List[str] = Field(default_factory=list)
    verification_plan: str = Field(default="")
    status: str = Field(default="PENDING_TEST")  # PENDING_TEST, VERIFIED, REFUTED
    category: str = Field(default="architecture")
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    @model_validator(mode="before")
    @classmethod
    def sync_pre_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            # Sync verification_plan list to str
            if isinstance(data.get("verification_plan"), list):
                data["verification_plan"] = "; ".join(str(x) for x in data["verification_plan"])
            if isinstance(data.get("falsification_conditions"), str):
                data["falsification_conditions"] = [data["falsification_conditions"]]
            if isinstance(data.get("evidence_references"), str):
                data["evidence_references"] = [data["evidence_references"]]

            # Sync evidence_references <-> supporting_evidence_ids
            if "evidence_references" in data and "supporting_evidence_ids" not in data:
                data["supporting_evidence_ids"] = list(data["evidence_references"])
            elif "supporting_evidence_ids" in data and "evidence_references" not in data:
                data["evidence_references"] = list(data["supporting_evidence_ids"])
            elif "supporting_evidence_ids" in data and "evidence_references" in data:
                refs = list(dict.fromkeys(data["supporting_evidence_ids"] + data["evidence_references"]))
                data["supporting_evidence_ids"] = refs
                data["evidence_references"] = refs
        return data

    @model_validator(mode="after")
    def compute_id_if_missing(self) -> "Hypothesis":
        if not self.hypothesis_id:
            h = hashlib.sha256(f"{self.statement}:{self.category}".encode("utf-8")).hexdigest()[:12]
            object.__setattr__(self, "hypothesis_id", f"HYP_{h}")
        if not self.supporting_evidence_ids and self.evidence_references:
            object.__setattr__(self, "supporting_evidence_ids", list(self.evidence_references))
        if not self.evidence_references and self.supporting_evidence_ids:
            object.__setattr__(self, "evidence_references", list(self.supporting_evidence_ids))
        return self


class HypothesisEngine:
    """Synthesizes empirical observations and research findings into rigorous,

    falsifiable hypotheses generated by Qwen.
    """

    def __init__(self):
        pass

    def generate_hypotheses(
        self,
        observations: List[ObservationRecord],
        findings: List[ResearchFinding],
        reasoning: Optional[StrategicReasoningResult] = None
    ) -> List[Hypothesis]:
        """Synthesizes observations and findings into testable, falsifiable hypotheses via Qwen."""
        hypotheses: List[Hypothesis] = []
        bundle = EvidenceBundle(observations=observations)

        try:
            # Qwen Foundation Model Hypothesis Generation
            qwen_hyps = qwen_reasoner.generate_hypotheses_from_evidence(
                bundle=bundle,
                findings=findings,
                reasoning=reasoning
            )

            for h_dict in qwen_hyps:
                if isinstance(h_dict, dict) and "statement" in h_dict:
                    conf = float(h_dict.get("confidence", 0.35))
                    falsif = h_dict.get("falsification_conditions", [])
                    if isinstance(falsif, str):
                        falsif = [falsif]
                    refs = h_dict.get("evidence_references", [])
                    if isinstance(refs, str):
                        refs = [refs]

                    hyp = Hypothesis(
                        statement=h_dict["statement"],
                        mechanism=h_dict.get("mechanism", "Software architectural causality"),
                        confidence=max(0.05, min(0.95, conf)),
                        evidence_references=refs,
                        supporting_evidence_ids=refs,
                        evidence_summary=h_dict.get("evidence_summary", ""),
                        falsification_conditions=falsif or ["Empirical test assertion failure"],
                        verification_plan=h_dict.get("verification_plan", "Run targeted test assertion verification."),
                        status="PENDING_TEST",
                        category=h_dict.get("category", "architecture")
                    )
                    hypotheses.append(hyp)

        except Exception as e:
            logger.warning(f"Qwen hypothesis generation fallback: {e}")

        # Fallback grounding strictly from findings citations if LLM call had an issue or was offline
        if not hypotheses and (findings or observations):
            lead_finding = findings[0] if findings else None
            lead_obs = observations[0] if observations else None
            src_ref = lead_finding.source_paths[0] if lead_finding and lead_finding.source_paths else (lead_obs.source if lead_obs else "workspace")
            evidence_cites = lead_finding.citations if lead_finding else [lead_obs.source]

            hypotheses.append(
                Hypothesis(
                    statement=f"Component '{src_ref}' maintains operational invariants verified by empirical observation.",
                    mechanism=f"AST and interface contracts observed in {src_ref}",
                    supporting_evidence_ids=evidence_cites,
                    evidence_references=evidence_cites,
                    evidence_summary=(lead_finding.finding_summary if lead_finding else lead_obs.evidence) if (lead_finding or lead_obs) else "Empirical scan",
                    falsification_conditions=[
                        f"Executing static AST verification or pytest on '{src_ref}' produces an exception."
                    ],
                    verification_plan=f"Execute pytest suite or AST parse against '{src_ref}'.",
                    confidence=0.35,
                    category="architecture"
                )
            )

        return hypotheses


# Singleton default instance
hypothesis_engine = HypothesisEngine()