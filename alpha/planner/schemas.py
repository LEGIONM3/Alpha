"""Schemas and contracts for the Planner component."""

import uuid
from typing import List, Optional
from datetime import datetime
from pydantic import BaseModel, Field
from alpha.core.types import ComplexityScore, ValidationType, utc_now

class ResourceEstimate(BaseModel):
    """Resource estimation for executing an atomic step on a small model."""
    estimated_input_tokens: int = 250
    estimated_output_tokens: int = 150
    timeout_seconds: float = 30.0
    tools_required: List[str] = Field(default_factory=list)

class ValidationContract(BaseModel):
    """Validation contract ensuring small model output correctness before continuing."""
    validation_type: ValidationType
    rule: str
    description: str
    is_mandatory: bool = True

class ExecutionStep(BaseModel):
    """An ordered, executable step with explicit resource boundaries and validation criteria."""
    step_number: int
    task_id: str
    name: str
    instruction: str
    complexity: ComplexityScore = ComplexityScore.LOW
    resources: ResourceEstimate = Field(default_factory=ResourceEstimate)
    blockers: List[str] = Field(default_factory=list)
    validation_contracts: List[ValidationContract] = Field(default_factory=list)
    fallback_strategy: Optional[str] = None

class ExecutionPlan(BaseModel):
    """Full execution plan generated by the Planner."""
    plan_id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    goal_id: str
    goal_description: str
    steps: List[ExecutionStep] = Field(default_factory=list)
    total_estimated_tokens: int = 0
    total_estimated_time_s: float = 0.0
    created_at: datetime = Field(default_factory=utc_now)

    def calculate_totals(self) -> None:
        self.total_estimated_tokens = sum(
            s.resources.estimated_input_tokens + s.resources.estimated_output_tokens 
            for s in self.steps
        )
        self.total_estimated_time_s = sum(s.resources.timeout_seconds for s in self.steps)
