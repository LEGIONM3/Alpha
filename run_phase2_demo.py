def run_scenario_f_multi_tool(aos: AlphaOperatingSystem) -> None:
    print_banner("Scenario F: Multi-Tool Workflow (DAG Orchestration, Parallel Waves & Reflection)")
    print("Goal: Execute coordinated multi-tool graph chaining Search -> Write -> Sandbox -> Diff -> Validation.")

    graph = ExecutionGraph(name="ScenarioF_MultiToolDAG")

    # Wave 1: Search and Read existing config concurrently
    node_search = ExecutionNode(
        node_id="f_search",
        tool_name="browser_search",
        arguments={"query": "python concurrency", "num_results": 1}
    )
    node_read_cfg = ExecutionNode(
        node_id="f_read_config",
        tool_name="fs_read_file",
        arguments={"file_path": "alpha/config.py", "max_lines": 20}
    )

    # Wave 2: Write integrated script depending on Wave 1
    script_path = str(aos.workspace_root / "data" / "multitool_task.py")
    node_write = ExecutionNode(
        node_id="f_write_script",
        tool_name="fs_write_file",
        arguments={
            "file_path": script_path,
            "content": "import time\nprint('Multi-tool DAG executed cleanly.')\n"
        },
        depends_on=["f_search", "f_read_config"]
    )

    # Wave 3: Sandbox execution
    node_sandbox = ExecutionNode(
        node_id="f_run_sandbox",
        tool_name="sandbox_execute_code",
        arguments={"language": "python", "code": "import sys; print('DAG child process OK')"},
        depends_on=["f_write_script"]
    )

    # Wave 4: Validation
    node_verify = ExecutionNode(
        node_id="f_verify",
        tool_name="verify_output_consistency",
        arguments={"output_text": "{{f_run_sandbox.output}}", "required_keywords": ["DAG child process OK"]},
        depends_on=["f_run_sandbox"]
    )

    graph.add_node(node_search)
    graph.add_node(node_read_cfg)
    graph.add_node(node_write)
    graph.add_node(node_sandbox)
    graph.add_node(node_verify)

    print("Executing Multi-Tool DAG...")
    graph_res = aos.execute_graph(graph)

    print(f"\nExecution Result: Success={graph_res.success}")
    print(f"Total Nodes: {graph_res.total_nodes} | Completed: {graph_res.completed_nodes} | Failed: {graph_res.failed_nodes}")
    print(f"Total Execution Time: {graph_res.execution_time_ms:.1f} ms")


